/// Validate a response `body` for an operation identified by `operation_id` at
/// `status`. Returns the list of violations (empty = conformant). The pure
/// core of the contract check, used directly by the crate's tests; the outbound
/// `guard` reaches the same logic via `validate_against_op` on a route match. If
/// the operation or status has no schema, returns no violations.
#[allow(dead_code)]
pub fn validate_operation(operation_id: &str, status: u16, body: &Value) -> Vec<Violation> {
    let store = contract();
    let Some(&idx) = store.by_id.get(operation_id) else {
        return Vec::new();
    };
    validate_against_op(&store.defs, &store.ops[idx], status, body)
}

fn validate_against_op(
    defs: &serde_json::Map<String, Value>,
    op: &Operation,
    status: u16,
    body: &Value,
) -> Vec<Violation> {
    let Some(schema) = op.responses.get(&status) else {
        return Vec::new();
    };
    let mut out = Vec::new();
    validate(defs, schema, body, "", &mut out, 0);
    out
}

/// True when `operation_id` is wired to the engine (i.e. its success path is
/// subject to validation). Part of the pure API exercised by tests.
#[allow(dead_code)]
pub fn is_implemented(operation_id: &str) -> bool {
    let store = contract();
    store
        .by_id
        .get(operation_id)
        .map(|&idx| store.ops[idx].implemented)
        .unwrap_or(false)
}

