fn is_json_content_type(resp: &Response) -> bool {
    resp.headers()
        .get(CONTENT_TYPE)
        .and_then(|v| v.to_str().ok())
        .map(|ct| {
            let ct = ct.to_ascii_lowercase();
            ct.starts_with("application/json") || ct.starts_with("application/problem+json")
        })
        .unwrap_or(false)
}

/// The response's declared body size, if it carries a parseable `Content-Length`.
fn content_length(resp: &Response) -> Option<usize> {
    resp.headers()
        .get(CONTENT_LENGTH)
        .and_then(|v| v.to_str().ok())
        .and_then(|s| s.trim().parse::<usize>().ok())
}

/// Outbound response-contract guard. Applied to the generated `/v2` router so it
/// sees the serialized body just before it goes on the wire, keyed by the
/// matched route + status. Only implemented operations with a JSON body for the
/// returned status are validated; everything else (unimplemented 501 stubs,
/// non-JSON/binary/streaming bodies, unmatched routes) passes through untouched
/// and un-buffered.
pub async fn guard(req: Request, next: Next) -> Response {
    guard_with_mode(req, next, mode()).await
}

async fn guard_with_mode(req: Request, next: Next, current_mode: Mode) -> Response {
    guard_impl(req, next, current_mode, max_buffer_bytes()).await
}

async fn guard_impl(req: Request, next: Next, current_mode: Mode, max_bytes: usize) -> Response {
    if current_mode == Mode::Off {
        return next.run(req).await;
    }

    let method = req.method().as_str().to_string();
    let matched = req
        .extensions()
        .get::<MatchedPath>()
        .map(|m| m.as_str().to_string());

    let resp = next.run(req).await;

    // Resolve the operation for this route; bail out (untouched) if unknown or
    // not an implemented op.
    let Some(matched) = matched else {
        return resp;
    };
    let route_key = format!("{method} {}", normalize_path(&matched));
    let store = contract();
    let Some(&op_idx) = store.by_route.get(&route_key) else {
        return resp;
    };
    let op = &store.ops[op_idx];
    if !op.implemented {
        return resp;
    }

    let status = resp.status().as_u16();
    if !op.responses.contains_key(&status) {
        return resp;
    }
    if !is_json_content_type(&resp) {
        return resp;
    }

    // Bound the memory validation is willing to buffer. If the response already
    // declares a body larger than the limit, skip validation and pass it through
    // untouched rather than buffering it — this avoids consuming the body and
    // prevents an OOM/DoS from a very large page.
    if let Some(len) = content_length(&resp)
        && len > max_bytes
    {
        tracing::warn!(
            target: "response_contract",
            operation = %op.operation_id,
            status,
            content_length = len,
            max_bytes,
            "response body exceeds contract-validation buffer limit; passing through unvalidated"
        );
        return resp;
    }

    // Buffer the (JSON) body so we can validate it, then either pass it through
    // or replace it with a 500. `to_bytes` is capped at `max_bytes` so a missing
    // or dishonest Content-Length still can't force an unbounded buffer; if the
    // body streams past the cap `to_bytes` errors and we fail loudly below.
    let (parts, body) = resp.into_parts();
    let bytes = match axum::body::to_bytes(body, max_bytes).await {
        Ok(b) => b,
        Err(err) => {
            // The body stream is now partially consumed and unrecoverable, so we
            // cannot pass the original response through. Returning `parts` with an
            // empty body would ship a corrupt response (e.g. a stale
            // Content-Length that no longer matches the empty body) and bury the
            // I/O error. Fail loudly with a structured 500 instead.
            tracing::error!(
                target: "response_contract",
                operation = %op.operation_id,
                status,
                "failed to buffer response body for contract validation: {err}"
            );
            return buffer_failure_response(&op.operation_id, status);
        }
    };

    let violations = match serde_json::from_slice::<Value>(&bytes) {
        Ok(value) => validate_against_op(&store.defs, op, status, &value),
        Err(err) => vec![Violation::new(
            "",
            "type",
            format!("response body is not valid JSON: {err}"),
        )],
    };

    if violations.is_empty() {
        return Response::from_parts(parts, Body::from(bytes));
    }

    match current_mode {
        Mode::Lenient => {
            tracing::warn!(
                target: "response_contract",
                operation = %op.operation_id,
                status,
                violations = violations.len(),
                "response contract violation (lenient: passing through): {:?}",
                violations
            );
            Response::from_parts(parts, Body::from(bytes))
        }
        // Strict (Off handled above).
        _ => {
            tracing::error!(
                target: "response_contract",
                operation = %op.operation_id,
                status,
                violations = violations.len(),
                "response contract violation -> 500: {:?}",
                violations
            );
            violation_response(&op.operation_id, status, &violations)
        }
    }
}

fn violation_response(operation_id: &str, status: u16, violations: &[Violation]) -> Response {
    let body = serde_json::json!({
        "error": "response_contract_violation",
        "message": "The gateway produced a response that violates its own OpenAPI contract; \
                    failing loudly to surface contract drift (see Magikcraft/nano-bpm#1011).",
        "operationId": operation_id,
        "status": status,
        "violations": violations,
    });
    Response::builder()
        .status(StatusCode::INTERNAL_SERVER_ERROR)
        .header(CONTENT_TYPE, "application/json")
        .body(Body::from(body.to_string()))
        .unwrap_or_else(|_| {
            let mut fallback = Response::new(Body::from("response_contract_violation"));
            *fallback.status_mut() = StatusCode::INTERNAL_SERVER_ERROR;
            fallback
        })
}

/// Structured 500 for when the response body could not be buffered for
/// validation. The body stream is unrecoverable at that point, so we cannot pass
/// the original response through without risking a corrupt (mismatched
/// Content-Length) reply; fail loudly instead.
fn buffer_failure_response(operation_id: &str, status: u16) -> Response {
    let body = serde_json::json!({
        "error": "response_contract_buffer_failed",
        "message": "The gateway could not buffer its own response body to validate it \
                    against its OpenAPI contract; failing loudly rather than shipping a \
                    possibly-corrupt response (see Magikcraft/nano-bpm#1011).",
        "operationId": operation_id,
        "status": status,
    });
    Response::builder()
        .status(StatusCode::INTERNAL_SERVER_ERROR)
        .header(CONTENT_TYPE, "application/json")
        .body(Body::from(body.to_string()))
        .unwrap_or_else(|_| {
            let mut fallback = Response::new(Body::from("response_contract_buffer_failed"));
            *fallback.status_mut() = StatusCode::INTERNAL_SERVER_ERROR;
            fallback
        })
}

