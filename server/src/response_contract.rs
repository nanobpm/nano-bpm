/// End-to-end tests over the outbound guard: a crafted response flows through a
/// real axum Router + the `guard` layer, exercising route matching (MatchedPath),
/// status/schema lookup, and the strict 500-on-violation rewrite.
#[cfg(test)]
mod middleware_tests {
    use axum::Router;
    use axum::routing::post;
    use serde_json::json;
    use tower::ServiceExt;

    use super::*;

    const WAIT_STATES_ROUTE: &str = "/v2/element-instances/wait-states/search";

    fn conformant_wait_state_body() -> Value {
        json!({
            "page": {"totalItems": 1, "hasMoreTotalItems": false,
                     "startCursor": null, "endCursor": null},
            "items": [{
                "processInstanceKey": "1",
                "elementInstanceKey": "2",
                "elementId": "task",
                "elementType": "SERVICE_TASK",
                "tenantId": "<default>",
                "rootProcessInstanceKey": "1",
                "bpmnProcessId": "proc",
                "details": {
                    "waitStateType": "JOB",
                    "jobKey": "9",
                    "jobType": "worker-a",
                    "jobKind": "BPMN_ELEMENT",
                    "listenerEventType": null,
                    "retries": 3
                }
            }]
        })
    }

    fn json_response(status: u16, body: Value) -> Response {
        Response::builder()
            .status(status)
            .header(CONTENT_TYPE, "application/json")
            .body(Body::from(body.to_string()))
            .unwrap()
    }

    fn app_with_guard(route: &str, mode: Mode, handler_status: u16, body: Value) -> Router {
        Router::new()
            .route(
                route,
                post(move || {
                    let body = body.clone();
                    async move { json_response(handler_status, body) }
                }),
            )
            .layer(axum::middleware::from_fn(move |req, next| {
                guard_with_mode(req, next, mode)
            }))
    }

    async fn run(app: Router) -> (u16, Value) {
        let req = Request::builder()
            .method("POST")
            .uri(WAIT_STATES_ROUTE)
            .body(Body::empty())
            .unwrap();
        let resp = app.oneshot(req).await.unwrap();
        let status = resp.status().as_u16();
        let bytes = axum::body::to_bytes(resp.into_body(), usize::MAX)
            .await
            .unwrap();
        let value = serde_json::from_slice(&bytes).unwrap_or(Value::Null);
        (status, value)
    }

    /// Acceptance: a response missing a `required` field returns 500 with a body
    /// naming the violation (the #1010 repro: a JOB wait state with no jobType).
    #[tokio::test]
    async fn missing_required_field_returns_500() {
        let mut body = conformant_wait_state_body();
        body["items"][0]["details"]
            .as_object_mut()
            .unwrap()
            .remove("jobType");

        let app = app_with_guard(WAIT_STATES_ROUTE, Mode::Strict, 200, body);
        let (status, value) = run(app).await;

        assert_eq!(status, 500, "a required-field violation must become a 500");
        assert_eq!(value["error"], "response_contract_violation");
        assert_eq!(value["operationId"], "searchElementInstanceWaitStates");
        assert_eq!(value["status"], 200);
        let violations = value["violations"].as_array().unwrap();
        assert!(
            violations
                .iter()
                .any(|v| v["rule"] == "required"
                    && v["detail"].as_str().unwrap().contains("jobType")),
            "500 body must name the jobType violation, got {value}"
        );
    }

    /// Acceptance: a conformant response passes through untouched (same status,
    /// same body).
    #[tokio::test]
    async fn conformant_response_passes_untouched() {
        let body = conformant_wait_state_body();
        let app = app_with_guard(WAIT_STATES_ROUTE, Mode::Strict, 200, body.clone());
        let (status, value) = run(app).await;
        assert_eq!(status, 200);
        assert_eq!(value, body);
    }

    /// In lenient mode a violation is logged but the (non-conformant) response is
    /// still returned unchanged — the prod-safe toggle.
    #[tokio::test]
    async fn lenient_mode_passes_violation_through() {
        let mut body = conformant_wait_state_body();
        body["items"][0]["details"]
            .as_object_mut()
            .unwrap()
            .remove("jobType");
        let app = app_with_guard(WAIT_STATES_ROUTE, Mode::Lenient, 200, body.clone());
        let (status, value) = run(app).await;
        assert_eq!(status, 200, "lenient mode must not rewrite to 500");
        assert_eq!(value, body);
    }

    /// Acceptance: an unimplemented operation still returns 501 — the guard never
    /// reinterprets a stub's 501 as a 500. `createUser` is a 501 stub (not in
    /// OVERRIDES), so its route is not validated.
    #[tokio::test]
    async fn unimplemented_operation_still_returns_501() {
        assert!(
            !is_implemented("createUser"),
            "test precondition: createUser is an unwired stub"
        );
        // The generated stub returns 501 with no JSON body; the guard must pass
        // it straight through.
        let route = "/v2/users";
        let app = Router::new()
            .route(
                route,
                post(|| async { Response::builder().status(501).body(Body::empty()).unwrap() }),
            )
            .layer(axum::middleware::from_fn(move |req, next| {
                guard_with_mode(req, next, Mode::Strict)
            }));
        let req = Request::builder()
            .method("POST")
            .uri(route)
            .body(Body::empty())
            .unwrap();
        let resp = app.oneshot(req).await.unwrap();
        assert_eq!(resp.status().as_u16(), 501);
    }

    /// A non-JSON body (e.g. XML) on an implemented op is never buffered or
    /// validated — it passes through untouched even in strict mode.
    #[tokio::test]
    async fn non_json_body_passes_through() {
        // get_process_definition_xml is implemented and returns XML.
        let route = "/v2/process-definitions/{processDefinitionKey}/xml";
        let app = Router::new()
            .route(
                route,
                axum::routing::get(|| async {
                    Response::builder()
                        .status(200)
                        .header(CONTENT_TYPE, "text/xml")
                        .body(Body::from("<definitions/>"))
                        .unwrap()
                }),
            )
            .layer(axum::middleware::from_fn(move |req, next| {
                guard_with_mode(req, next, Mode::Strict)
            }));
        let req = Request::builder()
            .method("GET")
            .uri("/v2/process-definitions/42/xml")
            .body(Body::empty())
            .unwrap();
        let resp = app.oneshot(req).await.unwrap();
        assert_eq!(resp.status().as_u16(), 200);
        let bytes = axum::body::to_bytes(resp.into_body(), usize::MAX)
            .await
            .unwrap();
        assert_eq!(&bytes[..], b"<definitions/>");
    }

    /// A response whose declared `Content-Length` exceeds the buffer limit is
    /// passed through unvalidated — the guard must not buffer it (OOM/DoS guard).
    /// Proven by using a body that *would* violate the contract: with the
    /// oversized Content-Length the guard skips validation and returns it as-is
    /// (200) instead of rewriting to 500.
    #[tokio::test]
    async fn oversized_content_length_passes_through_unvalidated() {
        let mut body = conformant_wait_state_body();
        body["items"][0]["details"]
            .as_object_mut()
            .unwrap()
            .remove("jobType");
        let serialized = body.to_string();
        let app = Router::new()
            .route(
                WAIT_STATES_ROUTE,
                post(move || {
                    let serialized = serialized.clone();
                    async move {
                        Response::builder()
                            .status(200)
                            .header(CONTENT_TYPE, "application/json")
                            // Declare a body far larger than the tiny limit below.
                            .header(CONTENT_LENGTH, "10000000")
                            .body(Body::from(serialized))
                            .unwrap()
                    }
                }),
            )
            .layer(axum::middleware::from_fn(move |req, next| {
                guard_impl(req, next, Mode::Strict, 16)
            }));
        let req = Request::builder()
            .method("POST")
            .uri(WAIT_STATES_ROUTE)
            .body(Body::empty())
            .unwrap();
        let resp = app.oneshot(req).await.unwrap();
        assert_eq!(
            resp.status().as_u16(),
            200,
            "oversized response must pass through unvalidated, not be rewritten to 500"
        );
    }

    /// A response with no honest length that streams past the buffer cap can't be
    /// buffered, so the guard fails loudly with a structured 500 rather than
    /// buffering unbounded memory. This is the bound that prevents OOM when
    /// Content-Length is absent or dishonest.
    #[tokio::test]
    async fn body_exceeding_cap_without_length_fails_loudly() {
        // A conformant body, but the cap is set below its size so it can't be
        // buffered. No Content-Length header is set, so the pre-check can't
        // short-circuit — the cap on `to_bytes` is what bounds memory.
        let body = conformant_wait_state_body();
        let serialized = body.to_string();
        assert!(
            serialized.len() > 16,
            "test needs a body larger than the cap"
        );
        let app = Router::new()
            .route(
                WAIT_STATES_ROUTE,
                post(move || {
                    let serialized = serialized.clone();
                    async move {
                        Response::builder()
                            .status(200)
                            .header(CONTENT_TYPE, "application/json")
                            .body(Body::from(serialized))
                            .unwrap()
                    }
                }),
            )
            .layer(axum::middleware::from_fn(move |req, next| {
                guard_impl(req, next, Mode::Strict, 16)
            }));
        let req = Request::builder()
            .method("POST")
            .uri(WAIT_STATES_ROUTE)
            .body(Body::empty())
            .unwrap();
        let resp = app.oneshot(req).await.unwrap();
        assert_eq!(resp.status().as_u16(), 500);
        let bytes = axum::body::to_bytes(resp.into_body(), usize::MAX)
            .await
            .unwrap();
        let value: Value = serde_json::from_slice(&bytes).unwrap_or(Value::Null);
        assert_eq!(value["error"], "response_contract_buffer_failed");
    }
}
