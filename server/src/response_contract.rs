const MAX_DEPTH: usize = 256;

fn json_type_matches(ty: &str, instance: &Value) -> bool {
    match ty {
        "null" => instance.is_null(),
        "boolean" => instance.is_boolean(),
        "string" => instance.is_string(),
        "number" => instance.is_number(),
        "integer" => {
            instance.is_i64()
                || instance.is_u64()
                || instance
                    .as_f64()
                    .is_some_and(|f| f.fract() == 0.0 && f.is_finite())
        }
        "object" => instance.is_object(),
        "array" => instance.is_array(),
        _ => true, // unknown type keyword: don't assert
    }
}

fn type_name(instance: &Value) -> &'static str {
    match instance {
        Value::Null => "null",
        Value::Bool(_) => "boolean",
        Value::Number(_) => "number",
        Value::String(_) => "string",
        Value::Array(_) => "array",
        Value::Object(_) => "object",
    }
}

fn child_pointer(pointer: &str, token: &str) -> String {
    // RFC 6901 escaping.
    let escaped = token.replace('~', "~0").replace('/', "~1");
    format!("{pointer}/{escaped}")
}

/// Validate `instance` against `schema`, appending any violations to `out`.
fn validate(
    defs: &serde_json::Map<String, Value>,
    schema: &Value,
    instance: &Value,
    pointer: &str,
    out: &mut Vec<Violation>,
    depth: usize,
) {
    if depth > MAX_DEPTH {
        // The recursion guard is a drift-detection surface: silently returning
        // here would accept the value, turning a pathologically deep response
        // (or a cyclic `$ref` alias) into a false negative. Surface it as a
        // structured violation so the guard fails loudly instead of quietly
        // treating an unvalidated value as conformant.
        out.push(Violation::new(
            pointer,
            "depth",
            format!("validation depth exceeded {MAX_DEPTH} levels"),
        ));
        return;
    }
    let Some(obj) = schema.as_object() else {
        // `true`/`{}` accept anything; `false` rejects everything.
        if schema.as_bool() == Some(false) {
            out.push(Violation::new(
                pointer,
                "schema",
                "schema `false` rejects all values",
            ));
        }
        return;
    };

    // $ref -> resolve within the shared defs pool.
    if let Some(reference) = obj.get("$ref").and_then(Value::as_str) {
        if let Some(name) = reference.strip_prefix("#/defs/")
            && let Some(target) = defs.get(name)
        {
            validate(defs, target, instance, pointer, out, depth + 1);
        }
        return;
    }

    // type
    if let Some(ty) = obj.get("type") {
        let ok = match ty {
            Value::String(s) => json_type_matches(s, instance),
            Value::Array(list) => list
                .iter()
                .filter_map(Value::as_str)
                .any(|s| json_type_matches(s, instance)),
            _ => true,
        };
        if !ok {
            let expected = match ty {
                Value::String(s) => s.clone(),
                other => other.to_string(),
            };
            out.push(Violation::new(
                pointer,
                "type",
                format!("expected type {expected}, got {}", type_name(instance)),
            ));
            // A wrong-typed value can't meaningfully satisfy the object/array
            // sub-checks below; stop here to avoid cascading noise.
            return;
        }
    }

    // enum
    if let Some(Value::Array(values)) = obj.get("enum")
        && !values.iter().any(|v| v == instance)
    {
        out.push(Violation::new(
            pointer,
            "enum",
            format!(
                "value {} is not one of the permitted enum values",
                compact(instance)
            ),
        ));
    }

    // const
    if let Some(expected) = obj.get("const")
        && expected != instance
    {
        out.push(Violation::new(
            pointer,
            "const",
            format!(
                "value {} does not equal the required const",
                compact(instance)
            ),
        ));
    }

    // allOf: every subschema must hold.
    if let Some(Value::Array(subs)) = obj.get("allOf") {
        for sub in subs {
            validate(defs, sub, instance, pointer, out, depth + 1);
        }
    }

    // anyOf / oneOf: at least one subschema must hold. (oneOf is validated with
    // anyOf semantics — >= 1 — because the spec's discriminated unions overlap
    // structurally and strict exactly-one would false-positive.)
    //
    // On failure we surface the violations of the *most likely intended* branch
    // (fewest violations) rather than an opaque "matches nothing" — critically,
    // for the pervasive `nullable` idiom (`anyOf: [ {type: null}, <schema> ]`) on
    // a non-null value we skip the null branch so the precise inner pointer/rule
    // (e.g. `…/jobType: required property missing`) reaches the caller.
    for key in ["anyOf", "oneOf"] {
        if let Some(Value::Array(subs)) = obj.get(key) {
            let mut matched = false;
            let mut best: Option<Vec<Violation>> = None;
            for sub in subs {
                let branch = branch_violations(defs, sub, instance, pointer, depth + 1);
                if branch.is_empty() {
                    matched = true;
                    break;
                }
                // Prefer a structural branch over the null alternative when the
                // value isn't null.
                if is_null_type_schema(sub) && !instance.is_null() {
                    continue;
                }
                if best.as_ref().is_none_or(|b| branch.len() < b.len()) {
                    best = Some(branch);
                }
            }
            if !matched {
                match best {
                    Some(mut branch) => out.append(&mut branch),
                    None => out.push(Violation::new(
                        pointer,
                        key,
                        format!("value does not match any of the {key} permitted schemas"),
                    )),
                }
            }
        }
    }

    // Object facets.
    if let Some(map) = instance.as_object() {
        if let Some(Value::Array(required)) = obj.get("required") {
            for req in required.iter().filter_map(Value::as_str) {
                if !map.contains_key(req) {
                    out.push(Violation::new(
                        &child_pointer(pointer, req),
                        "required",
                        format!("required property missing: {req}"),
                    ));
                }
            }
        }

        let properties = obj.get("properties").and_then(Value::as_object);
        if let Some(props) = properties {
            for (name, sub) in props {
                if let Some(child) = map.get(name) {
                    validate(
                        defs,
                        sub,
                        child,
                        &child_pointer(pointer, name),
                        out,
                        depth + 1,
                    );
                }
            }
        }

        match obj.get("additionalProperties") {
            Some(Value::Bool(false)) => {
                for name in map.keys() {
                    let known = properties.is_some_and(|p| p.contains_key(name));
                    if !known {
                        out.push(Violation::new(
                            &child_pointer(pointer, name),
                            "additionalProperties",
                            format!("unexpected property not permitted by the schema: {name}"),
                        ));
                    }
                }
            }
            Some(ap @ Value::Object(_)) => {
                for (name, child) in map {
                    let known = properties.is_some_and(|p| p.contains_key(name));
                    if !known {
                        validate(
                            defs,
                            ap,
                            child,
                            &child_pointer(pointer, name),
                            out,
                            depth + 1,
                        );
                    }
                }
            }
            _ => {}
        }
    }

    // Array items.
    if let (Some(items_schema), Some(arr)) = (obj.get("items"), instance.as_array()) {
        for (idx, elem) in arr.iter().enumerate() {
            validate(
                defs,
                items_schema,
                elem,
                &child_pointer(pointer, &idx.to_string()),
                out,
                depth + 1,
            );
        }
    }
}

/// Validate one `anyOf`/`oneOf` branch, returning its violations (at the real
/// `pointer`) without mutating the parent's list.
fn branch_violations(
    defs: &serde_json::Map<String, Value>,
    schema: &Value,
    instance: &Value,
    pointer: &str,
    depth: usize,
) -> Vec<Violation> {
    let mut scratch = Vec::new();
    validate(defs, schema, instance, pointer, &mut scratch, depth);
    scratch
}

/// True for the `{ "type": "null" }` sentinel the generator emits for the
/// `nullable` alternative.
fn is_null_type_schema(schema: &Value) -> bool {
    schema
        .as_object()
        .and_then(|o| o.get("type"))
        .and_then(Value::as_str)
        == Some("null")
}

fn compact(value: &Value) -> String {
    let s = value.to_string();
    // Truncate on a char boundary: `&s[..80]` would panic if byte 80 landed in
    // the middle of a multi-byte UTF-8 codepoint (turning a contract violation
    // into a 500 + panic instead of a structured error).
    match s.char_indices().nth(80) {
        Some((idx, _)) => format!("{}…", &s[..idx]),
        None => s,
    }
}

