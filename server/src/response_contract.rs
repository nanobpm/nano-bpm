//! Spec-generated response-contract validation for the REST gateway
//! (Magikcraft/nano-bpm#1011).
//!
//! For every **implemented** operation this validates the outgoing response
//! (status code + serialized JSON body) against the OpenAPI response schema for
//! that exact status. On a violation it fails loudly with **500** and a
//! machine-readable body naming the offending JSON Pointer(s) and rule(s) —
//! turning silent contract drift (the motivating case: a JOB wait state missing
//! the required `details.jobType`, silently skipped by a Zeebe-correct client,
//! see #1010) into an immediate, attributable error at the source.
//!
//! Derivation over duplication: the per-`(operationId, status)` schemas are NOT
//! hand-written. They are generated from the same `spec/` tree that generates
//! the server, by `scripts/gen-response-contract.py`, into the git-ignored
//! `response_contract_schema.json` bundled here via `include_str!`. Because that
//! bundle is regenerated by `make generate` (which CI runs before every build,
//! exactly as it does for the git-ignored `generated/` crate and
//! `stub_impls.rs`), the validators can never be stale versus the spec.
//!
//! Scope guard: only operations wired to the engine (the `implemented` flag,
//! sourced from `gen-stub-server.py`'s OVERRIDES map) are validated. Every
//! unwired operation returns `Err(())` -> `501 Not Implemented` and is left
//! untouched, so a 501 stub is never reinterpreted as a 500.
//!
//! Enforced JSON-Schema facets: `type`, `required`, `enum`/`const`, `nullable`
//! (translated to an explicit null alternative at generation time), plus
//! `allOf`/`anyOf`/`oneOf`, `items`, `properties`, and `additionalProperties`.
//! `format` and numeric range facets are carried but treated as annotations
//! (not asserted) to avoid false-positive 500s on the hot path from
//! Camunda-specific/custom formats.

use std::collections::HashMap;
use std::sync::OnceLock;

use axum::body::Body;
use axum::extract::{MatchedPath, Request};
use axum::middleware::Next;
use axum::response::Response;
use http::StatusCode;
use http::header::{CONTENT_LENGTH, CONTENT_TYPE};
use serde::Serialize;
use serde_json::Value;

/// The generated contract bundle (git-ignored, produced by `make generate`).
const CONTRACT_JSON: &str = include_str!("response_contract_schema.json");

/// Runtime enforcement mode, from `NANOBPM_RESPONSE_VALIDATION`.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Mode {
    /// Validate and fail with 500 on any violation (default; always-on in
    /// dev/CI/`urban check`-style runs).
    Strict,
    /// Validate and log a warning, but pass the response through unchanged. The
    /// prod-safe toggle for aggressive adoption without a hot-path foot-gun.
    Lenient,
    /// Disabled: no buffering, no validation, zero overhead.
    Off,
}

fn parse_mode(raw: Option<&str>) -> Mode {
    match raw.map(|s| s.trim().to_ascii_lowercase()).as_deref() {
        Some("off") | Some("disabled") | Some("false") | Some("0") | Some("none") => Mode::Off,
        Some("lenient") | Some("warn") | Some("observe") => Mode::Lenient,
        // Unset, "strict", "on", "1", or anything else -> strict (fail loud).
        _ => Mode::Strict,
    }
}

fn mode() -> Mode {
    static MODE: OnceLock<Mode> = OnceLock::new();
    *MODE.get_or_init(|| parse_mode(std::env::var("NANOBPM_RESPONSE_VALIDATION").ok().as_deref()))
}

/// Default ceiling (bytes) on how much response body the guard will buffer for
/// validation when no smaller limit is configured. Validation is inherently
/// O(body size) in memory, so this caps a single response's footprint. 8 MiB
/// comfortably covers realistic JSON pages while preventing a very large
/// response (or a large `pageSize`) from forcing an unbounded buffer (OOM/DoS).
const DEFAULT_MAX_BUFFER_BYTES: usize = 8 * 1024 * 1024;

fn parse_max_bytes(raw: Option<&str>) -> usize {
    raw.map(str::trim)
        .and_then(|s| s.parse::<usize>().ok())
        .filter(|&n| n > 0)
        .unwrap_or(DEFAULT_MAX_BUFFER_BYTES)
}

/// Maximum response body size (bytes) the guard will buffer for validation,
/// from `NANOBPM_RESPONSE_VALIDATION_MAX_BYTES` (default 8 MiB). A response that
/// declares a larger body via `Content-Length` is passed through unvalidated
/// (never buffered). A response with a missing or dishonest length that streams
/// past this cap cannot be passed through (its body is already partly consumed),
/// so the guard fails loudly with a structured 500 instead. Either way,
/// validation can never buffer more than this and exhaust memory.
fn max_buffer_bytes() -> usize {
    static MAX: OnceLock<usize> = OnceLock::new();
    *MAX.get_or_init(|| {
        parse_max_bytes(
            std::env::var("NANOBPM_RESPONSE_VALIDATION_MAX_BYTES")
                .ok()
                .as_deref(),
        )
    })
}

/// A single contract violation, machine-readable in the 500 body.
#[derive(Debug, Clone, Serialize, PartialEq, Eq)]
pub struct Violation {
    /// RFC 6901 JSON Pointer into the response body (`""` = the whole body).
    pub pointer: String,
    /// The failing schema rule, e.g. `required`, `type`, `enum`.
    pub rule: String,
    /// Human-readable detail, e.g. `required property missing: jobType`.
    pub detail: String,
}

impl Violation {
    fn new(pointer: &str, rule: &str, detail: impl Into<String>) -> Self {
        Violation {
            pointer: pointer.to_string(),
            rule: rule.to_string(),
            detail: detail.into(),
        }
    }
}

struct Operation {
    operation_id: String,
    implemented: bool,
    /// status code -> translated JSON-Schema for that response body.
    responses: HashMap<u16, Value>,
}

/// The parsed, indexed response contract.
struct Contract {
    /// Shared `$defs` pool referenced as `#/defs/<Name>`.
    defs: serde_json::Map<String, Value>,
    /// Every operation with at least one JSON response schema.
    ops: Vec<Operation>,
    /// `"<METHOD> <normalized-path>"` -> index into `ops` (outbound guard).
    by_route: HashMap<String, usize>,
    /// operationId -> index into `ops`. Direct-by-id lookup backs the pure
    /// `validate_operation`/`is_implemented` API (exercised by the crate's
    /// tests); the hot path uses `by_route`.
    #[allow(dead_code)]
    by_id: HashMap<String, usize>,
}

fn contract() -> &'static Contract {
    static STORE: OnceLock<Contract> = OnceLock::new();
    STORE.get_or_init(load_contract)
}

fn load_contract() -> Contract {
    let root: Value = serde_json::from_str(CONTRACT_JSON).expect(
        "response_contract_schema.json is not valid JSON (regenerate with `make generate`)",
    );

    let defs = root
        .get("defs")
        .and_then(Value::as_object)
        .cloned()
        .unwrap_or_default();

    let mut ops: Vec<Operation> = Vec::new();
    let mut by_route: HashMap<String, usize> = HashMap::new();
    let mut by_id: HashMap<String, usize> = HashMap::new();

    if let Some(list) = root.get("operations").and_then(Value::as_array) {
        for entry in list {
            let operation_id = entry
                .get("operationId")
                .and_then(Value::as_str)
                .unwrap_or_default()
                .to_string();
            let method = entry
                .get("method")
                .and_then(Value::as_str)
                .unwrap_or_default();
            let path = entry
                .get("path")
                .and_then(Value::as_str)
                .unwrap_or_default();
            let implemented = entry
                .get("implemented")
                .and_then(Value::as_bool)
                .unwrap_or(false);

            let mut responses: HashMap<u16, Value> = HashMap::new();
            if let Some(resp_map) = entry.get("responses").and_then(Value::as_object) {
                for (status, schema) in resp_map {
                    if let Ok(code) = status.parse::<u16>() {
                        responses.insert(code, schema.clone());
                    }
                }
            }

            let route_key = format!("{method} {}", normalize_path(path));
            let idx = ops.len();
            by_id.insert(operation_id.clone(), idx);
            by_route.insert(route_key, idx);
            ops.push(Operation {
                operation_id,
                implemented,
                responses,
            });
        }
    }

    Contract {
        defs,
        ops,
        by_route,
        by_id,
    }
}

/// `/v2/foo/{barKey}` -> `/v2/foo/{}` so route lookup is independent of the
/// (differently-cased) path-parameter names the axum router uses.
fn normalize_path(path: &str) -> String {
    let mut out = String::with_capacity(path.len());
    let mut in_param = false;
    for ch in path.chars() {
        match ch {
            '{' => {
                in_param = true;
                out.push('{');
            }
            '}' => {
                in_param = false;
                out.push('}');
            }
            _ if in_param => {}
            _ => out.push(ch),
        }
    }
    out
}

