//! Build script: stamps `NANOBPM_VERSION` (via the shared [`nano_version_stamp`]
//! helper, ADR 0064) and derives the cluster **determinism upgrade-boundary
//! table** (#1702) from the append-only boundary ledger
//! (`engine-core/examples/determinism/upgrade-boundaries.json`), cross-checked
//! against the previous-release divergence allowlist.
//!
//! Every allowlist entry declaring `"upgrade": "upgrade-boundary"` makes its
//! `introduced_in` release a **boundary**: Raft members re-execute committed
//! commands (ADR 0066, "Rolling upgrade", option C), so a mixed-version cluster
//! spanning that release would journal different events for the same command.
//! Allowlist entries EXPIRE (the determinism gate's `check_expiry`), but the
//! join restriction never does — so the table comes from the ledger, and the
//! build FAILS when a live allowlist boundary entry is missing from it. The
//! derivation itself lives in `src/boundary_ledger.rs` (unit-tested there).

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

#[path = "src/boundary_ledger.rs"]
#[allow(
    dead_code,
    reason = "shared with the crate; build.rs uses `derive` only"
)]
mod boundary_ledger;

fn main() {
    nano_version_stamp::emit();

    let manifest = env::var("CARGO_MANIFEST_DIR").unwrap_or_default();
    let dir = Path::new(&manifest).join("../../../engine-core/examples/determinism");
    let allowlist_path = dir.join("divergence-allowlist.json");
    let ledger_path = dir.join("upgrade-boundaries.json");
    // `emit()` already opts this script out of Cargo's default change
    // heuristic, so watch the inputs explicitly.
    println!("cargo:rerun-if-changed={}", allowlist_path.display());
    println!("cargo:rerun-if-changed={}", ledger_path.display());
    println!("cargo:rerun-if-changed=src/boundary_ledger.rs");

    let read =
        |p: &Path| fs::read_to_string(p).unwrap_or_else(|e| panic!("read {}: {e}", p.display()));
    let boundaries = boundary_ledger::derive(&read(&ledger_path), &read(&allowlist_path))
        .unwrap_or_else(|e| panic!("#1702 upgrade-boundary derivation: {e}"));

    let mut out = String::from(
        "// @generated by nano-falcon-protocol/build.rs from \
         engine-core/examples/determinism/upgrade-boundaries.json — do not edit.\n\
         // #1702: the determinism upgrade boundaries the cluster-join handshake enforces.\n",
    );
    out.push_str("pub const UPGRADE_BOUNDARIES: &[UpgradeBoundary] = &[\n");
    for (version, entries) in &boundaries {
        out.push_str("    UpgradeBoundary {\n");
        out.push_str(&format!("        version: {version:?},\n"));
        out.push_str("        entries: &[\n");
        for label in entries {
            out.push_str(&format!("            {label:?},\n"));
        }
        out.push_str("        ],\n    },\n");
    }
    out.push_str("];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap_or_default());
    fs::write(out_dir.join("upgrade_boundaries.rs"), out)
        .unwrap_or_else(|e| panic!("write upgrade_boundaries.rs: {e}"));
}
