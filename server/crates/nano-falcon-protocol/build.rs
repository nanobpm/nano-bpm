//! Build script: stamps `NANOBPM_VERSION` (via the shared [`nano_version_stamp`]
//! helper, ADR 0064) and derives the cluster **determinism upgrade-boundary
//! table** (#1702) from the previous-release divergence allowlist — the single
//! source of truth (`engine-core/examples/determinism/divergence-allowlist.json`).
//!
//! Every allowlist entry declaring `"upgrade": "upgrade-boundary"` makes its
//! `introduced_in` release a **boundary**: Raft members re-execute committed
//! commands (ADR 0066, "Rolling upgrade", option C), so a mixed-version cluster
//! spanning that release would journal different events for the same command.
//! The generated table (`UPGRADE_BOUNDARIES` in `cluster_join`) is what the
//! join handshake enforces — never a hand-maintained constant, so a release
//! that adds or expires an allowlist entry automatically re-derives it.

use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

use serde::Deserialize;

/// The allowlist fields this derivation reads. Field names mirror the file;
/// unknown fields are ignored (the determinism gate owns the strict schema).
#[derive(Deserialize)]
struct Allowlist {
    #[serde(default)]
    observational_variants: Vec<Entry>,
    #[serde(default)]
    divergences: Vec<Entry>,
}

#[derive(Deserialize)]
struct Entry {
    /// `scenario` (divergences) or `variant` (observational variants).
    #[serde(alias = "variant")]
    scenario: String,
    introduced_in: String,
    issue: String,
    upgrade: String,
}

fn main() {
    nano_version_stamp::emit();

    let manifest = env::var("CARGO_MANIFEST_DIR").unwrap_or_default();
    let allowlist_path = Path::new(&manifest)
        .join("../../../engine-core/examples/determinism/divergence-allowlist.json");
    // `emit()` already opts this script out of Cargo's default change
    // heuristic, so watch the input explicitly: editing the allowlist must
    // re-derive the table.
    println!("cargo:rerun-if-changed={}", allowlist_path.display());

    let text = fs::read_to_string(&allowlist_path)
        .unwrap_or_else(|e| panic!("read {}: {e}", allowlist_path.display()));
    let allowlist: Allowlist = serde_json::from_str(&text)
        .unwrap_or_else(|e| panic!("parse {}: {e}", allowlist_path.display()));

    // Group the upgrade-boundary entries by the release that introduces them,
    // sorted ascending so the FIRST boundary at/above a version is decisive.
    let mut by_release: BTreeMap<(u64, u64, u64), (String, Vec<String>)> = BTreeMap::new();
    for entry in allowlist
        .observational_variants
        .iter()
        .chain(allowlist.divergences.iter())
        .filter(|e| e.upgrade == "upgrade-boundary")
    {
        let version = entry.introduced_in.trim_start_matches('v').to_string();
        let triple = parse_release(&version).unwrap_or_else(|| {
            panic!(
                "allowlist introduced_in {:?} is not a release tag",
                entry.introduced_in
            )
        });
        let label = format!("{} ({})", entry.scenario, entry.issue);
        by_release
            .entry(triple)
            .or_insert_with(|| (version, Vec::new()))
            .1
            .push(label);
    }

    let mut out = String::from(
        "// @generated by nano-falcon-protocol/build.rs from \
         engine-core/examples/determinism/divergence-allowlist.json — do not edit.\n\
         // #1702: the determinism upgrade boundaries the cluster-join handshake enforces.\n",
    );
    out.push_str("pub const UPGRADE_BOUNDARIES: &[UpgradeBoundary] = &[\n");
    for (version, entries) in by_release.values() {
        out.push_str("    UpgradeBoundary {\n");
        out.push_str(&format!("        version: {version:?},\n"));
        out.push_str("        entries: &[\n");
        for label in entries {
            out.push_str(&format!("            {label:?},\n"));
        }
        out.push_str("        ],\n    },\n");
    }
    out.push_str("];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap_or_default());
    fs::write(out_dir.join("upgrade_boundaries.rs"), out)
        .unwrap_or_else(|e| panic!("write upgrade_boundaries.rs: {e}"));
}

/// `vMAJOR.MINOR.PATCH` (leading `v` already stripped) as a sortable triple.
fn parse_release(version: &str) -> Option<(u64, u64, u64)> {
    let mut parts = version.split('.').map(|p| p.parse::<u64>().ok());
    match (parts.next(), parts.next(), parts.next(), parts.next()) {
        (Some(Some(a)), Some(Some(b)), Some(Some(c)), None) => Some((a, b, c)),
        _ => None,
    }
}
