import json

SNAP = "server/tests/mcp/tools-schema-snapshot.json"
d = json.load(open(SNAP))
tools = d["tools"]

def rust_json(value, indent):
    """Render a JSON value as a serde_json::json! macro body."""
    pad = "    " * indent
    pad1 = "    " * (indent + 1)
    if value is None:
        return "serde_json::Value::Null"
    if value is True:
        return "true"
    if value is False:
        return "false"
    if isinstance(value, (int, float)):
        return json.dumps(value)
    if isinstance(value, str):
        return "serde_json::json!(%s)" % json.dumps(value)
    if isinstance(value, list):
        if not value:
            return "serde_json::json!([])"
        items = ",\n".join(pad1 + rust_json(v, indent + 1) for v in value)
        return "serde_json::json!([\n" + items + "\n" + pad + "])"
    if isinstance(value, dict):
        if not value:
            return "serde_json::json!({})"
        parts = []
        for k, v in value.items():
            parts.append(pad1 + json.dumps(k) + ": " + rust_json(v, indent + 1))
        return "serde_json::json!({\n" + ",\n".join(parts) + "\n" + pad + "})"
    raise TypeError(value)

# We embed the inputSchema as a compact JSON string constant and parse once via
# serde_json. This avoids an enormous nested json! macro while keeping the
# literal byte-exact with the snapshot. The string is the canonical compact
# serialization (sorted keys as in the snapshot file order preserved by json).
out = []
out.append("// @generated by scripts/gen-mcp-cluster-schemas.py from")
out.append("// server/tests/mcp/tools-schema-snapshot.json — DO NOT EDIT by hand.")
out.append("// Regenerate: python3 scripts/gen-mcp-cluster-schemas.py > server/src/mcp/cluster_schemas.rs")
out.append("")
out.append("use serde_json::Value;")
out.append("")
out.append("/// One static cluster tool's advertised metadata, mirroring Camunda's")
out.append("/// `tools/list` entry (name, title, description, inputSchema, annotations).")
out.append("pub(crate) struct ClusterToolSchema {")
out.append("    pub(crate) name: &'static str,")
out.append("    pub(crate) description: &'static str,")
out.append("    pub(crate) read_only: bool,")
out.append("    /// The exact `inputSchema` JSON Camunda advertises (compact serialization).")
out.append("    pub(crate) input_schema_json: &'static str,")
out.append("}")
out.append("")
out.append("impl ClusterToolSchema {")
out.append("    pub(crate) fn input_schema(&self) -> Value {")
out.append("        serde_json::from_str(self.input_schema_json)")
out.append("            .unwrap_or(Value::Object(serde_json::Map::new()))")
out.append("    }")
out.append("}")
out.append("")
out.append("/// The 18 static cluster tools, in Camunda's snapshot order.")
out.append("pub(crate) const CLUSTER_TOOL_SCHEMAS: &[ClusterToolSchema] = &[")
for t in tools:
    name = t["name"]
    desc = t["description"]
    read_only = t.get("annotations", {}).get("readOnlyHint", False)
    schema = json.dumps(t["inputSchema"], separators=(",", ":"))
    out.append("    ClusterToolSchema {")
    out.append("        name: %s," % json.dumps(name))
    out.append("        description: %s," % json.dumps(desc))
    out.append("        read_only: %s," % ("true" if read_only else "false"))
    out.append("        input_schema_json: %s," % json.dumps(schema))
    out.append("    },")
out.append("];")
out.append("")
print("\n".join(out))
